alter table public.orders add column if not exists last_modified_by_role text;
alter table public.orders add column if not exists last_modified_by_name text;
alter table public.orders add column if not exists updated_at timestamptz not null default now();

create table if not exists public.order_change_log (
  id bigint generated by default as identity primary key,
  order_id bigint not null,
  change_type text not null check (change_type in ('created', 'updated', 'deleted')),
  actor_role text not null check (actor_role in ('admin', 'staff', 'customer', 'system')),
  actor_name text,
  actor_contact text,
  old_values jsonb,
  new_values jsonb,
  changed_at timestamptz not null default now()
);

create index if not exists order_change_log_order_idx
  on public.order_change_log(order_id, changed_at desc);
create index if not exists orders_updated_at_idx on public.orders(updated_at desc);
alter table public.order_change_log enable row level security;

create or replace function public.touch_order_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := clock_timestamp();
  return new;
end;
$$;

drop trigger if exists orders_touch_updated_at on public.orders;
create trigger orders_touch_updated_at
before update on public.orders
for each row execute function public.touch_order_updated_at();

create or replace function public.log_order_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_role text;
  actor_name text;
  changed_key text;
  changed_old_values jsonb := '{}'::jsonb;
  changed_new_values jsonb := '{}'::jsonb;
begin
  if tg_op = 'UPDATE' and
    (to_jsonb(new) - 'last_modified_by_role' - 'last_modified_by_name' - 'updated_at')
      is not distinct from
    (to_jsonb(old) - 'last_modified_by_role' - 'last_modified_by_name' - 'updated_at') then
    return new;
  end if;

  if tg_op = 'DELETE' then
    actor_role := coalesce(old.last_modified_by_role, 'system');
    actor_name := old.last_modified_by_name;
    insert into public.order_change_log (
      order_id, change_type, actor_role, actor_name, actor_contact, old_values
    ) values (
      old.id, 'deleted', actor_role, actor_name, old.phone,
      to_jsonb(old) - 'last_modified_by_role' - 'last_modified_by_name' - 'updated_at'
    );
    return old;
  end if;

  if tg_op = 'INSERT' then
    actor_role := case
      when nullif(trim(new.booking_staff_name), '') is not null then 'staff'
      else 'customer'
    end;
    actor_name := coalesce(nullif(trim(new.booking_staff_name), ''), new.customer_name);
    insert into public.order_change_log (
      order_id, change_type, actor_role, actor_name, actor_contact, new_values
    ) values (
      new.id, 'created', actor_role, actor_name, new.phone,
      to_jsonb(new) - 'last_modified_by_role' - 'last_modified_by_name' - 'updated_at'
    );
    return new;
  end if;

  actor_role := coalesce(new.last_modified_by_role, 'system');
  actor_name := new.last_modified_by_name;
  for changed_key in
    select key
    from jsonb_each(to_jsonb(new))
    where key not in ('last_modified_by_role', 'last_modified_by_name', 'updated_at')
  loop
    if (to_jsonb(old) -> changed_key) is distinct from (to_jsonb(new) -> changed_key) then
      changed_old_values := changed_old_values || jsonb_build_object(changed_key, to_jsonb(old) -> changed_key);
      changed_new_values := changed_new_values || jsonb_build_object(changed_key, to_jsonb(new) -> changed_key);
    end if;
  end loop;
  if changed_old_values = '{}'::jsonb then
    return new;
  end if;

  insert into public.order_change_log (
    order_id, change_type, actor_role, actor_name, actor_contact, old_values, new_values
  ) values (
    new.id, 'updated', actor_role, actor_name, new.phone,
    changed_old_values,
    changed_new_values
  );
  return new;
end;
$$;

drop trigger if exists orders_change_audit on public.orders;
create trigger orders_change_audit
after insert or update or delete on public.orders
for each row execute function public.log_order_changes();

create or replace function public.get_order_counts(
  p_from timestamptz,
  p_to timestamptz,
  p_regions text[],
  p_region_mode text default 'include'
)
returns table (booking_count bigint, confirmed_count bigint)
language sql
stable
security definer
set search_path = public
as $$
  select
    count(*) filter (where order_row.created_at >= p_from and order_row.created_at < p_to),
    count(*) filter (
      where case
        when jsonb_typeof(order_row.items) = 'array' then
          case
            when jsonb_array_length(order_row.items) > 0 then exists (
              select 1
              from jsonb_array_elements(order_row.items) as items(item_value)
              where item_value ->> 'item_status' in ('حجز مؤكد', 'قادم')
                or (
                  nullif(item_value ->> 'item_status', '') is null
                  and order_row.status in ('حجز مؤكد', 'قادم')
                )
              )
            else order_row.status in ('حجز مؤكد', 'قادم')
          end
        else order_row.status in ('حجز مؤكد', 'قادم')
      end
    )
  from public.orders as order_row
  where case
    when p_region_mode = 'exclude' then not exists (
      select 1
      from unnest(coalesce(p_regions, '{}'::text[])) as regions(region)
      where region = '*'
        or (
          position(' - ' in region) > 0
          and split_part(region, ' - ', 1) = order_row.governorate
          and substring(region from position(' - ' in region) + 3) = coalesce(order_row.district, '')
        )
        or (
          position(' - ' in region) = 0
          and region = order_row.governorate
          and order_row.district is null
        )
    )
    else exists (
      select 1
      from unnest(coalesce(p_regions, '{}'::text[])) as regions(region)
      where region = '*'
        or (
          position(' - ' in region) > 0
          and split_part(region, ' - ', 1) = order_row.governorate
          and substring(region from position(' - ' in region) + 3) = coalesce(order_row.district, '')
        )
        or (
          position(' - ' in region) = 0
          and region = order_row.governorate
          and order_row.district is null
        )
    )
  end;
$$;

revoke all on function public.get_order_counts(timestamptz, timestamptz, text[], text) from public, anon, authenticated;
grant execute on function public.get_order_counts(timestamptz, timestamptz, text[], text) to service_role;
