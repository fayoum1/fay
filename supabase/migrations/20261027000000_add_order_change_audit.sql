alter table public.orders add column if not exists last_modified_by_role text;
alter table public.orders add column if not exists last_modified_by_name text;

create table if not exists public.order_change_log (
  id bigint generated by default as identity primary key,
  order_id bigint not null,
  change_type text not null check (change_type in ('created', 'updated', 'deleted')),
  actor_role text not null check (actor_role in ('admin', 'staff', 'customer', 'system')),
  actor_name text,
  actor_contact text,
  old_values jsonb,
  new_values jsonb,
  changed_at timestamptz not null default now()
);
create index if not exists order_change_log_order_idx
  on public.order_change_log(order_id, changed_at desc);
alter table public.order_change_log enable row level security;

create or replace function public.log_order_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_role text;
  actor_name text;
begin
  if tg_op = 'UPDATE' and
    (to_jsonb(new) - 'last_modified_by_role' - 'last_modified_by_name')
      is not distinct from
    (to_jsonb(old) - 'last_modified_by_role' - 'last_modified_by_name') then
    return new;
  end if;

  if tg_op = 'DELETE' then
    actor_role := coalesce(old.last_modified_by_role, 'system');
    actor_name := old.last_modified_by_name;
    insert into public.order_change_log (
      order_id, change_type, actor_role, actor_name, actor_contact, old_values
    ) values (
      old.id, 'deleted', actor_role, actor_name, old.phone,
      to_jsonb(old) - 'last_modified_by_role' - 'last_modified_by_name'
    );
    return old;
  end if;

  if tg_op = 'INSERT' then
    actor_role := case
      when nullif(trim(new.booking_staff_name), '') is not null then 'staff'
      else 'customer'
    end;
    actor_name := coalesce(nullif(trim(new.booking_staff_name), ''), new.customer_name);
    insert into public.order_change_log (
      order_id, change_type, actor_role, actor_name, actor_contact, new_values
    ) values (
      new.id, 'created', actor_role, actor_name, new.phone,
      to_jsonb(new) - 'last_modified_by_role' - 'last_modified_by_name'
    );
    return new;
  end if;

  actor_role := coalesce(new.last_modified_by_role, 'system');
  actor_name := new.last_modified_by_name;
  insert into public.order_change_log (
    order_id, change_type, actor_role, actor_name, actor_contact, old_values, new_values
  ) values (
    new.id, 'updated', actor_role, actor_name, new.phone,
    to_jsonb(old) - 'last_modified_by_role' - 'last_modified_by_name',
    to_jsonb(new) - 'last_modified_by_role' - 'last_modified_by_name'
  );
  return new;
end;
$$;

drop trigger if exists orders_change_audit on public.orders;
create trigger orders_change_audit
after insert or update or delete on public.orders
for each row execute function public.log_order_changes();
